"""Build an original rooftop bluebird and matching Roblox geometry."""
import bpy
import json
import math
from pathlib import Path
from mathutils import Vector
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets/characters/bird"
OUT.mkdir(parents=True, exist_ok=True)
bpy.ops.object.select_all(action="SELECT")
bpy.ops.object.delete(use_global=False)
parts = []
def sphere(name, center, size, color, leg=0):
    parts.append(dict(name=name, kind="ball", center=center, size=size, color=color, leg=leg))
def rod(name, a, b, width, color, leg):
    parts.append(dict(name=name, kind="rod", a=a, b=b, width=width, color=color, leg=leg))
blue=(.12,.38,.66)
dark=(.06,.19,.34)
cream=(.91,.85,.65)
orange=(.95,.49,.10)
sphere("Body",(0,0,1.35),(2.4,3.2,2.3),blue)
sphere("Breast",(0,.95,1.15),(1.85,1.4,1.8),cream)
sphere("Head",(0,1.1,2.35),(1.9,1.9,1.8),blue)
sphere("Beak",(0,2.05,2.05),(.9,1.25,.5),orange)
sphere("LowerBeak",(0,2.02,1.85),(.8,1.0,.22),orange)
for side in (-1,1):
    group=1 if side<0 else 2
    sphere("Wing"+str(group),(side*1.65,-.15,1.65),(2.5,1.9,.48),dark,group)
    for i in range(4):
        sphere("Feather"+str(group)+"_"+str(i),(side*(2.2+i*.3),-.5+i*.36,1.58),(1.7, .55,.3),blue,group)
    sphere("EyeWhite"+str(side),(side*.65,1.85,2.65),(.7,.45,.8),(.98,.97,.89))
    sphere("Pupil"+str(side),(side*.65,2.05,2.65),(.35,.14,.47),(.015,.02,.03))
    sphere("EyeSpark"+str(side),(side*.59,2.13,2.77),(.12,.06,.13),(1,1,1))
    rod("Leg"+str(side),(side*.55,0,.7),(side*.55,.1,.25),.16,orange,0)
    for toe in (-1,0,1):
        rod("Toe"+str(side)+"_"+str(toe),(side*.55,.1,.2),(side*.55+toe*.22,.7,.12),.13,orange,0)
for i in (-1,0,1):
    sphere("Tail"+str(i),(i*.48,-1.8,1.45),(.7,2.0,.35),dark)
sphere("Crest",(0,.8,3.15),(.55,1.0,.35),dark)
materials={}
for p in parts:
    color=tuple(p["color"])
    if color not in materials:
        mat=bpy.data.materials.new("BirdColor"+str(len(materials)))
        mat.diffuse_color=(*color,1); mat.use_nodes=True
        mat.node_tree.nodes["Principled BSDF"].inputs["Base Color"].default_value=(*color,1)
        mat.node_tree.nodes["Principled BSDF"].inputs["Roughness"].default_value=.4
        materials[color]=mat
    if p["kind"]=="ball":
        bpy.ops.mesh.primitive_uv_sphere_add(segments=20, ring_count=12, location=p["center"])
        obj=bpy.context.object; obj.scale=Vector(p["size"])/2
    else:
        a,b=Vector(p["a"]),Vector(p["b"])
        bpy.ops.mesh.primitive_cylinder_add(vertices=12, radius=p["width"]/2, depth=(b-a).length, location=(a+b)/2)
        obj=bpy.context.object; obj.rotation_euler=(b-a).to_track_quat("Z","Y").to_euler()
    obj.name=p["name"]; obj.data.materials.append(materials[color])
    for face in obj.data.polygons: face.use_smooth=True
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
bpy.ops.object.select_all(action="SELECT")
bpy.ops.export_scene.fbx(filepath=str(OUT/"RooftopBird.fbx"),use_selection=True,object_types={"MESH"},axis_forward="-Z",axis_up="Y",bake_anim=False)
def vec(v):
    return "Vector3.new("+",".join(f"{n:.5g}" for n in (v[0],v[2],-v[1]))+")"
lines=["--!strict","-- Generated by scripts/build_bird.py; same authored shapes as the Blender model.","return {"]
for p in parts:
    fields=['name="'+p["name"]+'"','kind="'+p["kind"]+'"',"leg="+str(p["leg"]),"color=Color3.new("+",".join(str(n) for n in p["color"])+")"]
    if p["kind"]=="ball":
        fields += ["center="+vec(p["center"]),"size=Vector3.new("+",".join(str(n) for n in (p["size"][0],p["size"][2],p["size"][1]))+")"]
    else:
        fields += ["a="+vec(p["a"]),"b="+vec(p["b"]),"width="+str(p["width"])]
    lines.append(" {"+",".join(fields)+"},")
lines.append("}")
(ROOT/"src/shared/BirdGeometry.luau").write_text("\n".join(lines)+"\n",encoding="utf-8")
(OUT/"manifest.json").write_text(json.dumps({"wing_groups":2,"parts":len(parts),"original_art":True,"source":"scripts/build_bird.py"},indent=2)+"\n")
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/"RooftopBird.blend"))
bpy.ops.mesh.primitive_plane_add(size=200)
floor=bpy.context.object
mat=bpy.data.materials.new("Backdrop"); mat.diffuse_color=(.11,.15,.18,1); floor.data.materials.append(mat)
for location,energy,size in [((3,4,7),1100,5),((-4,1,4),750,4),((0,-4,6),1000,3)]:
    bpy.ops.object.light_add(type="AREA",location=location)
    light=bpy.context.object; light.data.energy=energy; light.data.shape="DISK"; light.data.size=size
    light.rotation_euler=(Vector((0,0,1))-light.location).to_track_quat("-Z","Y").to_euler()
bpy.ops.object.camera_add(location=(6,8,5))
cam=bpy.context.object; cam.rotation_euler=(Vector((0,0,1))-cam.location).to_track_quat("-Z","Y").to_euler()
cam.data.type="ORTHO"; cam.data.ortho_scale=10
scene=bpy.context.scene; scene.camera=cam; scene.render.engine="CYCLES"; scene.cycles.samples=32
scene.render.resolution_x=1000; scene.render.resolution_y=800; scene.render.resolution_percentage=100
scene.world.color=(.2,.2,.2); scene.render.filepath=str(OUT/"preview.png")
bpy.ops.render.render(write_still=True)
